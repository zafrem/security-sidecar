'use strict';
// Cloudflare Pages _headers + WAF expression converter (opt-in).
// Handles sidecars whose enforcement.via includes waf, ip-allowlist, or api-gateway.
const RANK = { public: 1, authenticated: 2, internal: 3 };

function toCfPath(route) {
  return route
    .replace(/\/\[\[\.\.\.([^\]]+)\]\]/g, '/*')
    .replace(/\/\[\.\.\.([^\]]+)\]/g, '/*')
    .replace(/\/\[([^\]]+)\]/g, '/:$1');
}

function wafExpr(route) {
  const dyn = /\[[^\]]+\]/.test(route);
  if (!dyn) return `http.request.uri.path eq "${route}"`;
  const prefix = route.split('/[')[0] || '/';
  return `starts_with(http.request.uri.path, "${prefix}/")`;
}

function render(entries) {
  const wafInternal = [];
  const wafAuth = [];
  const blocks = [];

  for (const e of entries) {
    const policies = Object.entries(e.methods);
    const [, top] = policies.slice().sort((a, b) => RANK[b[1].exposure] - RANK[a[1].exposure])[0];
    if (top.exposure === 'internal') wafInternal.push(wafExpr(e.route));
    if (top.exposure === 'authenticated') wafAuth.push(wafExpr(e.route));

    const hdrs = [];
    if (top.cache && top.cache.policy && top.cache.policy !== 'unspecified') {
      const v = top.cache.policy === 'no-store'
        ? 'no-store'
        : `${top.cache.policy}${top.cache.maxAgeSec ? `, max-age=${top.cache.maxAgeSec}` : ''}`;
      hdrs.push(`  Cache-Control: ${v}`);
    }
    if (top.indexing === 'noindex') hdrs.push('  X-Robots-Tag: noindex');
    if (hdrs.length) {
      blocks.push([`# ${e.source} (${top.exposure})`, toCfPath(e.route), ...hdrs].join('\n'));
    }
  }

  const lines = [
    '# Generated by security-sidecar compile --target cloudflare. Do not edit by hand.',
  ];
  if (wafInternal.length) {
    lines.push(`# WAF block/allowlist rule (internal): (${wafInternal.join(' or ')}) and not ip.src in $internal_ips`);
  }
  if (wafAuth.length) {
    lines.push(`# WAF auth-check rule (authenticated): (${wafAuth.join(' or ')})`);
  }
  lines.push('');
  if (blocks.length) lines.push(blocks.join('\n\n'), '');
  return lines.join('\n');
}

module.exports = { accepts: ['waf', 'ip-allowlist', 'api-gateway'], outFile: 'security-sidecar._headers', render };
