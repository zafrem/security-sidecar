'use strict';
// Nginx converter (opt-in). Handles sidecars whose enforcement.via is api-gateway or ip-allowlist.
const RANK = { public: 1, authenticated: 2, internal: 3 };

function locationFor(route) {
  const dyn = /\[[^\]]+\]/.test(route);
  if (!dyn) return `location = ${route}`;
  const re = route.replace(/\[\.\.\.[^\]]+\]|\[\[\.\.\.[^\]]+\]\]/g, '.+').replace(/\[[^\]]+\]/g, '[^/]+');
  return `location ~ ^${re}$`;
}

function render(entries) {
  const zones = []; const blocks = [];
  entries.forEach((e, i) => {
    const policies = Object.entries(e.methods);
    // Nginx locations are per-path; the most restrictive method wins (conservative).
    const [, top] = policies.slice().sort((a, b) => RANK[b[1].exposure] - RANK[a[1].exposure])[0];
    const lines = [`# ${e.source}${policies.length > 1 ? ` (methods: ${policies.map(([m]) => m).join(', ')}; strictest applied)` : ''}`];
    lines.push(`${locationFor(e.route)} {`);
    if (top.exposure === 'internal') lines.push('    allow 127.0.0.1;', '    allow ::1;', '    deny all;   # extend with your internal ranges');
    if (top.exposure === 'authenticated') lines.push('    auth_request /_auth;   # define an internal /_auth location for your auth service');
    if (top.cache) {
      const v = { 'no-store': 'no-store', private: `private${top.cache.maxAgeSec ? `, max-age=${top.cache.maxAgeSec}` : ''}`, public: `public${top.cache.maxAgeSec ? `, max-age=${top.cache.maxAgeSec}` : ''}` }[top.cache.policy];
      if (v) lines.push(`    add_header Cache-Control "${v}" always;`);
    }
    if (top.indexing === 'noindex') lines.push('    add_header X-Robots-Tag "noindex" always;');
    const rl = policies.map(([, p]) => p.rateLimit).filter(Boolean)[0];
    if (rl) {
      const rate = Math.max(1, Math.ceil((rl.max * 60000) / rl.windowMs));
      zones.push(`limit_req_zone $binary_remote_addr zone=ss_${i}:10m rate=${rate}r/m;`);
      lines.push(`    limit_req zone=ss_${i} burst=${rl.max} nodelay;`);
    }
    lines.push('    proxy_pass $upstream;   # set to your upstream', '}');
    blocks.push(lines.join('\n'));
  });
  return [
    '# Generated by security-sidecar compile --target nginx. Do not edit by hand.',
    '# Include inside your http/server context. limit_req_zone lines belong in http.',
    '',
    ...zones, zones.length ? '' : null,
    blocks.join('\n\n'), '',
  ].filter((x) => x !== null).join('\n');
}

module.exports = { accepts: ['api-gateway', 'ip-allowlist'], outFile: 'security-sidecar.nginx.conf', render };
