'use strict';
// Next.js converter (opt-in). Handles sidecars whose enforcement.via is app-middleware or api-gateway.
const RANK = { public: 1, authenticated: 2, internal: 3 };

function toNextSource(route) {
  return route
    .replace(/\/\[\[\.\.\.([^\]]+)\]\]/g, '/:$1*')
    .replace(/\/\[\.\.\.([^\]]+)\]/g, '/:$1*')
    .replace(/\/\[([^\]]+)\]/g, '/:$1');
}

function cacheHeader(cache) {
  if (!cache || !cache.policy || cache.policy === 'unspecified') return null;
  if (cache.policy === 'no-store') return 'no-store';
  const age = cache.maxAgeSec ? `, max-age=${cache.maxAgeSec}` : '';
  return `${cache.policy}${age}`;
}

function render(entries) {
  const rules = [];
  const headerEntries = [];
  for (const e of entries) {
    const policies = Object.entries(e.methods);
    const [, top] = policies.slice().sort((a, b) => RANK[b[1].exposure] - RANK[a[1].exposure])[0];
    const source = toNextSource(e.route);
    const cc = cacheHeader(top.cache);
    const rl = policies.map(([, p]) => p.rateLimit).filter(Boolean)[0] || null;
    rules.push({
      source: e.source,
      route: e.route,
      matcher: source,
      exposure: top.exposure,
      ...(cc ? { cacheControl: cc } : {}),
      ...(top.indexing ? { indexing: top.indexing } : {}),
      ...(rl ? { rateLimit: rl } : {}),
      ...(e.gate ? { gate: e.gate } : {}),
    });
    const headers = [];
    if (cc) headers.push({ key: 'Cache-Control', value: cc });
    if (top.indexing === 'noindex') headers.push({ key: 'X-Robots-Tag', value: 'noindex' });
    if (headers.length) headerEntries.push({ source, headers });
  }
  return [
    '// Generated by security-sidecar compile --target nextjs. Do not edit by hand.',
    '// Import headers in next.config.js or routePolicies in middleware.ts.',
    `'use strict';`,
    `const routePolicies = ${JSON.stringify(rules, null, 2)};`,
    `const headerRules = ${JSON.stringify(headerEntries, null, 2)};`,
    'async function headers() { return headerRules; }',
    'module.exports = { routePolicies, headers };',
    '',
  ].join('\n');
}

module.exports = { accepts: ['app-middleware', 'api-gateway'], outFile: 'security-sidecar.nextjs.js', render };
