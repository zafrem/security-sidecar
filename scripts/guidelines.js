'use strict';
// Builds every guideline output from guidelines/ (the single source).
//   node scripts/guidelines.js          write the files
//   require('./guidelines').build()     returns { relativePath: content } (used by tests)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8').replace(/\s+$/, '');

const DESCRIPTION = 'Secure-coding guidelines for code that handles external input. Use when writing or editing request handlers, API routes, server actions, or any function that takes user-controlled values (params, query, body, headers, cookies, uploads, environment, files, messages). Covers input validation, avoiding free types such as any, value constraints, ownership checks, injection, secrets and safe error handling, with notes for TypeScript, Python, Go and Java.';
const CURSOR_GLOBS = '**/*.{ts,tsx,js,jsx,mjs,py,go,java}';
const NOTE = 'Generated from guidelines/ by `npm run guidelines`. Do not edit this file; edit the source instead.';

function body() {
  const langs = fs.readdirSync(path.join(root, 'guidelines', 'languages')).filter((f) => f.endsWith('.md')).sort();
  return {
    langs,
    text: [
      '# Secure coding guidelines',
      '',
      'Apply these rules to code you write or change. They are guidance: nothing enforces them.',
      '',
      read('guidelines/core.md'),
      '',
      '## Language notes',
      '',
      'Apply the notes for the language you are writing. They add detail to the rules above.',
      '',
      ...langs.map((f) => read(`guidelines/languages/${f}`).replace(/^## /, '### ') + '\n'),
    ].join('\n').replace(/\s+$/, '') + '\n',
  };
}

// One line per rule (the bold headline), for the always-on session reminder.
function reminder() {
  const heads = [...read('guidelines/core.md').matchAll(/\*\*(SG-\d+\.[^*]+)\*\*/g)].map((m) => `- ${m[1].trim()}`);
  return [
    'security-sidecar: apply these security rules to ALL code you write or change in this project, not only web routes.',
    'Load the secure-functions skill for the details and the language notes.',
    '',
    ...heads,
    '',
    'If a rule conflicts with the request, do what is safe, say so briefly and offer the alternative. These rules are guidance: never claim code is secure or protected because you followed them.',
  ].join('\n') + '\n';
}

function build() {
  const { text } = body();
  const marked = (title) => `<!-- BEGIN security-sidecar guidelines -->\n<!-- ${NOTE} -->\n\n${text}\n<!-- END security-sidecar guidelines -->\n`;
  return {
    'plugins/security-sidecar/hooks/security-reminder.txt': reminder(),
    'plugins/security-sidecar/skills/secure-functions/SKILL.md':
      `---\nname: secure-functions\ndescription: ${DESCRIPTION}\n---\n\n<!-- ${NOTE} -->\n\n${text}`,
    'adapters/agents/AGENTS.md': marked(),
    'adapters/gemini/GEMINI.md': marked(),
    'adapters/cursor/security-sidecar.mdc':
      `---\ndescription: ${DESCRIPTION}\nglobs: ${CURSOR_GLOBS}\nalwaysApply: false\n---\n\n<!-- ${NOTE} -->\n\n${text}`,
  };
}

if (require.main === module) {
  for (const [rel, content] of Object.entries(build())) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), content);
    console.log('wrote', rel);
  }
}
module.exports = { build };
